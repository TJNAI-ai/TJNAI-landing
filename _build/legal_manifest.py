#!/usr/bin/env python3
"""Legal documents, versions and hashes for the clickwrap acceptance flow.

    python3 _build/legal_docs.py --import /workspace/legal   # refresh _build/legal_src/ from Lena's drafts
    python3 _build/legal_manifest.py --write                 # render pages, freeze, hash, regenerate outputs
    python3 _build/legal_manifest.py --check                 # verify everything is in sync (used by _checks)

Inputs (committed):
  _build/legal_versions.json   document IDs, versions, exact checkbox labels, flows (Lena's handoff v0.2)
  _build/pricing.json          every price shown by the flow (no prices are hard-coded anywhere else)
  _build/legal_src/*.md        Lena's drafts with internal notes stripped (see legal_docs.py)
  _build/legal_page.tmpl       the page shell (same styles as the old legal pages)

Outputs (generated, committed, never edited by hand):
  terms.html, privacy.html, refund.html, legal/msa.html, legal/sow-*.html   current version of each document
  legal/archive/<slug>/<version>.html   frozen artifact; content_sha256 = SHA-256 of these exact bytes
  _backend/acceptance/src/manifest.json what the Worker enforces
  agree.html between the ACCEPTANCE-BLOCK markers   what the browser shows

A frozen artifact is never rewritten. If a document's text changes while its latest version already has a
hash, --check and --write both fail until a new version entry is added (the legal owner sets
is_material_change). A flow can only require a document that is enabled and has a hashed version.

Note for when Lena revises the MSA box: the business-purpose sentence lives ONLY in the B2B-CONFIRM box. The
MSA label deliberately omits it (handoff §2.4 had both); do not re-add it to both boxes.
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from html import escape
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import legal_docs  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "_build/legal_versions.json"
PRICING = ROOT / "_build/pricing.json"
TEMPLATE = ROOT / "_build/legal_page.tmpl"
WORKER_MANIFEST = ROOT / "_backend/acceptance/src/manifest.json"
AGREE = ROOT / "agree.html"
BEGIN = "<!-- ACCEPTANCE-BLOCK:BEGIN generated by _build/legal_manifest.py; do not edit by hand -->"
END = "<!-- ACCEPTANCE-BLOCK:END -->"
VERSION_RE = re.compile(r"^v\d+\.\d+$")


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def load() -> tuple[dict, dict]:
    reg = json.loads(REGISTRY.read_text(encoding="utf-8"))
    prices = json.loads(PRICING.read_text(encoding="utf-8"))["prices"]
    return reg, prices


def fill(template: str, values: dict) -> str:
    def sub(m: re.Match) -> str:
        key = m.group(1)
        if key not in values:
            raise KeyError(f"unknown placeholder {{{key}}}")
        return values[key]
    return re.sub(r"\{([a-z_]+)\}", sub, template)


def plain(text: str) -> str:
    return re.sub(r"\*\*(.+?)\*\*", r"\1", text)


def strong(text: str) -> str:
    return re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", escape(text, quote=False))


def display_id(doc: dict, v: dict) -> str:
    return f"{doc['document_id']}-{v['version']}"


def artifact_rel(doc: dict, v: dict) -> str:
    return f"legal/archive/{doc['slug']}/{v['version']}.html"


def artifact_uri(doc: dict, v: dict) -> str:
    return f"/legal/archive/{doc['slug']}/{v['version']}"


def inline_text(doc: dict, v: dict, prices: dict) -> str:
    return fill(v["text"], {**prices, **v.get("variables", {})})


def inline_disclosure(doc: dict, v: dict, prices: dict) -> str | None:
    if "disclosure" not in v:
        return None
    return fill(v["disclosure"], {**prices, **v.get("variables", {})})


def label_plain(doc: dict, v: dict, prices: dict) -> str:
    if doc.get("inline"):
        return plain(inline_text(doc, v, prices))
    return "".join(v["label"])


def render_page(doc: dict, v: dict) -> str:
    md = (ROOT / v["source"]).read_text(encoding="utf-8")
    h1, body = legal_docs.render_main(md)
    if doc["page"].startswith("legal/"):
        head = '  <meta name="robots" content="noindex">'
    else:
        head = f'  <link rel="canonical" href="https://tjnai.ai{doc["public_path"]}">'
    label = f"{doc['title']} — {display_id(doc, v)} · Effective {v['effective']}"
    page = TEMPLATE.read_text(encoding="utf-8")
    for key, value in (
        ("head_meta", head),
        ("title", escape(doc["title"])),
        ("source", v["source"]),
        ("h1", h1),
        ("label", escape(label, quote=False)),
        ("body", body),
    ):
        page = page.replace("{{" + key + "}}", value)
    return page


def freeze(html: str) -> str:
    out = re.sub(r'\n  <link rel="canonical"[^>]*>', '\n  <meta name="robots" content="noindex">', html, count=1)
    return out


def worker_manifest(reg: dict, prices: dict) -> dict:
    docs = {}
    for doc in reg["documents"]:
        if not doc.get("enabled"):
            continue
        versions = []
        for v in doc["versions"]:
            entry = {
                "version": v["version"],
                "display_id": display_id(doc, v),
                "content_sha256": v["content_sha256"],
                "is_material_change": bool(v.get("is_material_change")),
                "artifact_uri": None if doc.get("inline") else artifact_uri(doc, v),
                "checkbox_text": label_plain(doc, v, prices),
            }
            disclosure = inline_disclosure(doc, v, prices) if doc.get("inline") else None
            if disclosure is not None:
                entry["billing_disclosure"] = plain(disclosure)
            versions.append(entry)
        material = [v for v in doc["versions"] if v.get("is_material_change")] or doc["versions"][:1]
        docs[doc["document_id"]] = {
            "title": doc["title"],
            "public_path": doc.get("public_path"),
            "current_version": doc["versions"][-1]["version"],
            "current_material_version": material[-1]["version"],
            "versions": versions,
        }
    flows = {k: {"page_or_flow": f["page_or_flow"], "required": f["required"]} for k, f in reg["flows"].items()}
    return {"_generated": "by _build/legal_manifest.py; do not edit", "documents": docs, "flows": flows}


def agree_block(reg: dict, prices: dict) -> str:
    docs = {d["document_id"]: d for d in reg["documents"]}
    flows = reg["flows"]
    L = [BEGIN]
    for flow_id, f in flows.items():
        L.append(f'      <p class="price-line" data-flow="{flow_id}" hidden><strong>Payment:</strong> {escape(fill(f["payment_note"], prices), quote=False)}</p>')
    bill = docs["BILLING-CONSENT"]
    bv = bill["versions"][-1]
    L.append('      <div class="key-terms" id="key-terms" data-flow="care-plan" hidden>')
    L.append('        <h2 class="billing-h">Key terms at a glance</h2>')
    L.append(f'        <p id="key-terms-text">{strong(inline_disclosure(bill, bv, prices))}</p>')
    L.append("      </div>")
    L.append('      <fieldset class="agree-group" id="agree-group">')
    L.append("        <legend>To continue, please read each document and check every box. None of the boxes is checked in advance.</legend>")
    for doc_id in reg["box_order"]:
        doc = docs[doc_id]
        if not doc.get("enabled"):
            continue
        v = doc["versions"][-1]
        in_flows = " ".join(k for k, f in flows.items() if doc_id in f["required"])
        box_id = "agree-" + doc_id.lower()
        attrs = (f'type="checkbox" id="{box_id}" name="accept" value="{doc_id}" data-document-id="{doc_id}"'
                 f' data-version="{v["version"]}" data-hash="{v["content_sha256"]}"')
        if doc.get("inline"):
            label = strong(inline_text(doc, v, prices))
        else:
            pre, link, post = v["label"]
            label = (f'{escape(pre, quote=False)}<a href="{artifact_uri(doc, v)}" target="_blank" rel="noopener">'
                     f'{escape(link, quote=False)}</a>{escape(post, quote=False)}')
        L.append(f'        <div class="agree-row" data-flows="{in_flows}" hidden><input {attrs} disabled> <label for="{box_id}">{label}</label></div>')
    L.append("      </fieldset>")
    flow_json = json.dumps({k: {"title": f["title"], "required": f["required"]} for k, f in flows.items()},
                           sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    L.append(f'      <script type="application/json" id="acceptance-flows">{flow_json}</script>')
    L.append("      " + END)
    return "\n".join(L)


def run(write: bool) -> list[str]:
    errors: list[str] = []
    reg, prices = load()
    known = {d["document_id"]: d for d in reg["documents"]}
    for doc in reg["documents"]:
        if not doc.get("enabled"):
            continue
        seen = set()
        for i, v in enumerate(doc["versions"]):
            name = display_id(doc, v)
            if not VERSION_RE.match(v["version"]):
                errors.append(f"{name}: version must look like v0.2")
            if v["version"] in seen:
                errors.append(f"{name}: version string reused")
            seen.add(v["version"])
            latest = i == len(doc["versions"]) - 1
            if doc.get("inline"):
                try:
                    actual = sha256_bytes(label_plain(doc, v, prices).encode("utf-8"))
                except KeyError as exc:
                    errors.append(f"{name}: {exc}")
                    continue
                if v["content_sha256"] is None and write:
                    v["content_sha256"] = actual
                elif v["content_sha256"] != actual:
                    errors.append(f"{name}: text (or a price in it) changed after hashing; add a new version entry")
                continue
            art = ROOT / artifact_rel(doc, v)
            if not latest:
                if not art.exists() or sha256_bytes(art.read_bytes()) != v["content_sha256"]:
                    errors.append(f"{artifact_rel(doc, v)}: frozen artifact missing or edited")
                continue
            if not (ROOT / v["source"]).exists():
                errors.append(f"{name}: source {v['source']} missing")
                continue
            page = render_page(doc, v)
            frozen = freeze(page).encode("utf-8")
            if v["content_sha256"] is not None and sha256_bytes(frozen) != v["content_sha256"]:
                errors.append(f"{name}: document text changed after it was frozen. Add a new version entry "
                              "to _build/legal_versions.json (legal owner sets is_material_change), then run --write.")
                continue
            if art.exists() and art.read_bytes() != frozen:
                errors.append(f"{artifact_rel(doc, v)}: frozen artifact was edited")
                continue
            if write:
                art.parent.mkdir(parents=True, exist_ok=True)
                if not art.exists():
                    art.write_bytes(frozen)
                v["content_sha256"] = sha256_bytes(frozen)
                (ROOT / doc["page"]).parent.mkdir(parents=True, exist_ok=True)
                (ROOT / doc["page"]).write_text(page, encoding="utf-8")
            else:
                if not art.exists():
                    errors.append(f"{artifact_rel(doc, v)} missing; run --write")
                if v["content_sha256"] is None:
                    errors.append(f"{name}: not hashed yet; run --write")
                if not (ROOT / doc["page"]).exists() or (ROOT / doc["page"]).read_text(encoding="utf-8") != page:
                    errors.append(f"{doc['page']} is not the rendered {name}; run --write")
    for flow, spec in reg["flows"].items():
        for doc_id in spec["required"]:
            doc = known.get(doc_id)
            if doc is None:
                errors.append(f"flow {flow} requires {doc_id}, which has no manifest entry")
            elif not doc.get("enabled"):
                errors.append(f"flow {flow} requires {doc_id}, which is not enabled")
            elif not doc["versions"] or (doc["versions"][-1]["content_sha256"] is None and not write):
                errors.append(f"flow {flow} requires {doc_id}, which has no hashed version")
        try:
            fill(spec["payment_note"], prices)
        except KeyError as exc:
            errors.append(f"flow {flow} payment_note: {exc}")
    if errors:
        return errors
    if write:
        REGISTRY.write_text(json.dumps(reg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    manifest = json.dumps(worker_manifest(reg, prices), indent=2, ensure_ascii=False) + "\n"
    agree = AGREE.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), flags=re.S)
    if not pattern.search(agree):
        return ["agree.html is missing the ACCEPTANCE-BLOCK markers"]
    new_agree = pattern.sub(lambda _: agree_block(reg, prices), agree, count=1)
    if write:
        WORKER_MANIFEST.write_text(manifest, encoding="utf-8")
        AGREE.write_text(new_agree, encoding="utf-8")
    else:
        if not WORKER_MANIFEST.exists() or WORKER_MANIFEST.read_text(encoding="utf-8") != manifest:
            errors.append("_backend/acceptance/src/manifest.json is stale; run --write")
        if new_agree != agree:
            errors.append("agree.html acceptance block is stale; run --write")
    return errors


def main() -> int:
    write = "--write" in sys.argv[1:]
    errors = run(write)
    for e in errors:
        print("legal_manifest:", e)
    if not errors:
        print("legal_manifest: " + ("written" if write else "in sync"))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
