#!/usr/bin/env python3
"""Legal document versions for the clickwrap acceptance flow.

    python3 _build/legal_manifest.py --check   # verify everything is in sync (used by _checks)
    python3 _build/legal_manifest.py --write   # fill new hashes, freeze artifacts, regenerate outputs

Source of truth: _build/legal_versions.json (edited by hand).

For each HTML legal document the content hash is SHA-256 (hex) of its canonical
text: the visible text inside <main>, HTML comments and tags removed, entities
decoded, whitespace collapsed to single spaces, UTF-8. Styling-only edits do not
change the hash; any wording change does, and then --check fails until a new
version entry is added (the legal owner decides is_material_change).

Each hashed version is frozen to legal/archive/<slug>/<version>.html (the page
as presented, with absolute asset paths, noindex and no canonical). A frozen
artifact is never rewritten: --write refuses if its text would change.

The inline BILLING-CONSENT document hashes the JSON
{"checkbox_text": ..., "disclosure": [...]} with sorted keys and no spaces.

Generated outputs (do not edit by hand):
  _backend/acceptance/src/manifest.json   what the Worker enforces
  agree.html, between the ACCEPTANCE-BLOCK markers   what the browser shows
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from html import escape, unescape
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "_build/legal_versions.json"
WORKER_MANIFEST = ROOT / "_backend/acceptance/src/manifest.json"
AGREE = ROOT / "agree.html"
BEGIN = "<!-- ACCEPTANCE-BLOCK:BEGIN generated by _build/legal_manifest.py; do not edit by hand -->"
END = "<!-- ACCEPTANCE-BLOCK:END -->"
VERSION_RE = re.compile(r"^\d{4}-\d{2}-\d{2}-\d+$")


def canonical_text(html: str) -> str:
    match = re.search(r"<main\b[^>]*>(.*?)</main>", html, flags=re.S | re.I)
    if not match:
        raise ValueError("no <main> element")
    body = re.sub(r"<!--.*?-->", " ", match.group(1), flags=re.S)
    body = re.sub(r"<(script|style)\b[^>]*>.*?</\1>", " ", body, flags=re.S | re.I)
    text = re.sub(r"<[^>]+>", " ", body)
    return re.sub(r"\s+", " ", unescape(text)).strip()


def sha256(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def inline_payload(version: dict) -> str:
    return json.dumps(
        {"checkbox_text": version["checkbox_text"], "disclosure": version["disclosure"]},
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    )


def freeze(html: str) -> str:
    """The page as presented, made to work from legal/archive/<slug>/."""
    out = re.sub(r'\s*<link rel="canonical"[^>]*>', "", html, count=1)
    out = out.replace(
        '<meta name="viewport" content="width=device-width,initial-scale=1">',
        '<meta name="viewport" content="width=device-width,initial-scale=1">\n  <meta name="robots" content="noindex">',
        1,
    )
    out = re.sub(r'(src|href)="assets/', r'\1="/assets/', out)
    out = out.replace("url('assets/", "url('/assets/")
    return out


def artifact_path(doc: dict, version: dict) -> Path:
    return ROOT / "legal/archive" / doc["slug"] / f"{version['version']}.html"


def artifact_uri(doc: dict, version: dict) -> str:
    return f"/legal/archive/{doc['slug']}/{version['version']}"


def label_text(doc: dict, version: dict) -> str:
    if doc.get("inline"):
        return version["checkbox_text"]
    return f"I agree to the {doc['title']} (version {version['version']})"


def current_material(doc: dict) -> dict:
    material = [v for v in doc["versions"] if v.get("is_material_change")]
    return material[-1] if material else doc["versions"][0]


def worker_manifest(reg: dict) -> dict:
    docs = {}
    for doc in reg["documents"]:
        versions = []
        for v in doc["versions"]:
            entry = {
                "version": v["version"],
                "content_sha256": v["content_sha256"],
                "is_material_change": bool(v.get("is_material_change")),
                "effective_at": v.get("effective_at"),
                "artifact_uri": None if doc.get("inline") else artifact_uri(doc, v),
                "checkbox_text": label_text(doc, v),
            }
            if doc.get("inline"):
                entry["disclosure"] = v["disclosure"]
            versions.append(entry)
        docs[doc["document_id"]] = {
            "title": doc["title"],
            "public_path": doc.get("public_path"),
            "current_version": doc["versions"][-1]["version"],
            "current_material_version": current_material(doc)["version"],
            "versions": versions,
        }
    return {
        "_generated": "by _build/legal_manifest.py from _build/legal_versions.json; do not edit",
        "documents": docs,
        "flows": reg["flows"],
        "pending_documents": sorted(reg.get("pending_documents", {})),
    }


def agree_block(reg: dict) -> str:
    docs = {d["document_id"]: d for d in reg["documents"]}
    lines = [BEGIN]
    lines.append('      <fieldset class="agree-group" id="agree-group">')
    lines.append('        <legend>To continue, please read and agree to each of the following. You must check every box. None of the boxes is checked in advance.</legend>')
    for doc_id in ("TOS", "PRIVACY", "REFUND"):
        doc = docs[doc_id]
        v = doc["versions"][-1]
        title = escape(doc["title"])
        uri = artifact_uri(doc, v)
        input_id = f"agree-{doc['slug']}"
        lines.append(
            f'        <div class="agree-row"><input type="checkbox" id="{input_id}" name="accept" value="{doc_id}"'
            f' data-document-id="{doc_id}" data-version="{v["version"]}" data-hash="{v["content_sha256"]}">'
            f' <label for="{input_id}" data-label>I agree to the <a href="{uri}" target="_blank" rel="noopener">{title}</a>'
            f' (version {v["version"]})</label></div>'
        )
    bill = docs["BILLING-CONSENT"]
    v = bill["versions"][-1]
    lines.append('        <div class="billing" id="billing-group" hidden>')
    lines.append('          <h2 class="billing-h">Recurring billing</h2>')
    lines.append('          <ul class="billing-terms">')
    for item in v["disclosure"]:
        lines.append(f"            <li>{escape(item)}</li>")
    lines.append("          </ul>")
    lines.append(
        f'          <div class="agree-row"><input type="checkbox" id="agree-billing" name="accept" value="BILLING-CONSENT"'
        f' data-document-id="BILLING-CONSENT" data-version="{v["version"]}" data-hash="{v["content_sha256"]}" disabled>'
        f' <label for="agree-billing" data-label>{escape(v["checkbox_text"])}</label></div>'
    )
    lines.append("        </div>")
    lines.append("      </fieldset>")
    flows = json.dumps(reg["flows"], sort_keys=True, separators=(",", ":"))
    lines.append(f'      <script type="application/json" id="acceptance-flows">{flows}</script>')
    lines.append("      " + END)
    return "\n".join(lines)


def run(write: bool) -> list[str]:
    errors: list[str] = []
    reg = json.loads(REGISTRY.read_text(encoding="utf-8"))
    for doc in reg["documents"]:
        seen = set()
        for i, v in enumerate(doc["versions"]):
            name = f"{doc['document_id']} {v['version']}"
            if not VERSION_RE.match(v["version"]):
                errors.append(f"{name}: version must look like YYYY-MM-DD-n")
            if v["version"] in seen:
                errors.append(f"{name}: version string reused")
            seen.add(v["version"])
            latest = i == len(doc["versions"]) - 1
            if doc.get("inline"):
                actual = sha256(inline_payload(v))
                if v["content_sha256"] is None and write:
                    v["content_sha256"] = actual
                elif v["content_sha256"] != actual:
                    errors.append(f"{name}: billing text changed after hashing; add a new version instead")
                continue
            path = artifact_path(doc, v)
            if latest:
                actual = sha256(canonical_text((ROOT / doc["source"]).read_text(encoding="utf-8")))
                if v["content_sha256"] is None:
                    if write:
                        v["content_sha256"] = actual
                    else:
                        errors.append(f"{name}: not hashed yet; run --write")
                        continue
                elif v["content_sha256"] != actual:
                    errors.append(
                        f"{doc['source']} wording changed but {name} is still the latest version. "
                        "Add a new version entry to _build/legal_versions.json (legal owner sets is_material_change), then run --write."
                    )
                    continue
                frozen = freeze((ROOT / doc["source"]).read_text(encoding="utf-8"))
                if path.exists():
                    if sha256(canonical_text(path.read_text(encoding="utf-8"))) != v["content_sha256"]:
                        errors.append(f"{path.relative_to(ROOT)}: frozen artifact text does not match {name}")
                elif write:
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(frozen, encoding="utf-8")
                else:
                    errors.append(f"{path.relative_to(ROOT)} missing; run --write")
            else:
                if not path.exists():
                    errors.append(f"{path.relative_to(ROOT)}: frozen artifact for an older version was removed")
                elif sha256(canonical_text(path.read_text(encoding="utf-8"))) != v["content_sha256"]:
                    errors.append(f"{path.relative_to(ROOT)}: frozen artifact was edited")
            shown = (ROOT / doc["source"]).read_text(encoding="utf-8") if latest else ""
            if latest and f"Version {v['version']}" not in canonical_text(shown):
                errors.append(f"{doc['source']} does not show 'Version {v['version']}'")
    for flow, spec in reg["flows"].items():
        known = {d["document_id"] for d in reg["documents"]}
        for doc_id in spec["required"]:
            if doc_id not in known:
                errors.append(f"flow {flow} requires unknown document {doc_id}")
    if errors:
        return errors
    if write:
        REGISTRY.write_text(json.dumps(reg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    manifest = json.dumps(worker_manifest(reg), indent=2, ensure_ascii=False) + "\n"
    block = agree_block(reg)
    agree = AGREE.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), flags=re.S)
    if not pattern.search(agree):
        return ["agree.html is missing the ACCEPTANCE-BLOCK markers"]
    new_agree = pattern.sub(lambda _: block.lstrip(), agree, count=1)
    if write:
        WORKER_MANIFEST.parent.mkdir(parents=True, exist_ok=True)
        WORKER_MANIFEST.write_text(manifest, encoding="utf-8")
        AGREE.write_text(new_agree, encoding="utf-8")
    else:
        if not WORKER_MANIFEST.exists() or WORKER_MANIFEST.read_text(encoding="utf-8") != manifest:
            errors.append("_backend/acceptance/src/manifest.json is stale; run --write")
        if new_agree != agree:
            errors.append("agree.html acceptance block is stale; run --write")
    return errors


def main() -> int:
    write = "--write" in sys.argv[1:]
    errors = run(write)
    for e in errors:
        print("legal_manifest:", e)
    if not errors:
        print("legal_manifest: " + ("written" if write else "in sync"))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
